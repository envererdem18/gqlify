import 'dart:convert';
import 'dart:io';

import 'package:gqlify/gqlify.dart';
import 'package:gqlify/src/schema/sdl_builder.dart';
import 'package:path/path.dart' as p;
import 'package:test/test.dart';

import 'support/introspection_writer.dart';

void main() {
  final fixture = Directory('test/fixtures/shop');
  String read(String name) =>
      File(p.join(fixture.path, name)).readAsStringSync();
  final sdl = read('schema.graphql');
  final documents = [
    for (final name in ['fragments.graphql', 'products.graphql'])
      GqlifySource('lib/$name', read(name)),
  ];

  GenerationResult run(
    String schemaPath,
    String content, {
    GenerationMode mode = GenerationMode.both,
  }) => GqlifyEngine().generate(
    GenerationInput(
      config: GqlifyConfig(schema: [schemaPath], mode: mode),
      schema: [GqlifySource(schemaPath, content)],
      documents: documents,
    ),
  );

  /// Outputs with the source-file header line and the schema library path
  /// normalized, which legitimately differ between the two inputs.
  Map<String, String> normalized(GenerationResult result, String schemaPath) =>
      {
        for (final MapEntry(:key, :value) in result.outputs.entries)
          key.replaceAll(schemaPath, 'SCHEMA'): value
              .replaceAll(RegExp('// Generated by gqlify from .*'), '')
              .replaceAll(p.basename(schemaPath), 'SCHEMA')
              .replaceAll(schemaPath, 'SCHEMA'),
      };

  test('introspection JSON generates the same code as the equivalent SDL', () {
    final sink = DiagnosticSink();
    final schema = parseSchema(sdl, sink)!;
    final json = jsonEncode(introspectionOf(schema));

    final fromSdl = run('lib/schema.graphql', sdl);
    final fromJson = run('lib/schema.json', json);

    expect(fromSdl.hasErrors, isFalse);
    expect(fromJson.diagnostics, fromSdl.diagnostics);
    expect(fromJson.outputs.keys, contains('lib/schema.json.dart'));
    expect(
      normalized(fromJson, 'lib/schema.json'),
      normalized(fromSdl, 'lib/schema.graphql'),
    );
  });

  test('accepts the bare __schema form', () {
    final sink = DiagnosticSink();
    final full = introspectionOf(parseSchema(sdl, sink)!);
    final bare = (full['data']! as Map)['__schema'];
    final result = run(
      'lib/schema.json',
      jsonEncode({'__schema': bare}),
      mode: GenerationMode.schemaOnly,
    );
    expect(result.diagnostics, isEmpty);
    expect(
      result.outputs['lib/schema.json.dart'],
      contains('enum ProductStatus'),
    );
  });

  test('reports malformed introspection', () {
    List<String> codes(String json) => [
      for (final d in run('lib/schema.json', json).diagnostics) d.code,
    ];
    expect(codes('{'), ['invalid-introspection']);
    expect(codes('{"data": {}}'), ['invalid-introspection']);
    expect(
      codes(
        '{"__schema": {"queryType": {"name": "Query"}, "types": [{"kind": "WAT", "name": "X"}]}}',
      ),
      ['invalid-introspection'],
    );
  });

  test('an introspection schema must be the only schema file', () {
    final result = GqlifyEngine().generate(
      GenerationInput(
        config: GqlifyConfig(schema: ['a.json', 'b.graphql']),
        schema: [
          GqlifySource('a.json', '{}'),
          GqlifySource('b.graphql', 'type Query { a: Int }'),
        ],
        documents: const [],
      ),
    );
    expect(result.diagnostics.single.code, 'invalid-config');
  });
}
