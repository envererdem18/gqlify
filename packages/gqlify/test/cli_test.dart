import 'dart:convert';
import 'dart:io';

import 'package:gqlify/src/cli/runner.dart';
import 'package:path/path.dart' as p;
import 'package:test/test.dart';

const _schema =
    'type Product { id: ID! name: String! } '
    'type Query { products: [Product!]! }';

void main() {
  late Directory dir;
  late StringBuffer out;
  late StringBuffer err;

  void write(String path, String content) {
    final file = File(p.join(dir.path, path));
    file.parent.createSync(recursive: true);
    file.writeAsStringSync(content);
  }

  File file(String path) => File(p.join(dir.path, path));

  setUp(() {
    dir = Directory.systemTemp.createTempSync('gqlify_cli_');
    write('gqlify.yaml', 'schema: lib/graphql/schema.graphql\n');
    write('lib/graphql/schema.graphql', _schema);
    write('lib/graphql/a.graphql', 'query A { products { id } }');
  });
  tearDown(() => dir.deleteSync(recursive: true));

  Future<int> run(List<String> args) {
    out = StringBuffer();
    err = StringBuffer();
    return GqlifyCommandRunner(
      out: out,
      err: err,
    ).run(['-C', dir.path, ...args]);
  }

  test('generate writes outputs and is a no-op when nothing changed', () async {
    expect(await run(['generate']), 0);
    expect(out.toString(), contains('2 created'));
    final output = file('lib/graphql/a.graphql.dart');
    final modified = output.lastModifiedSync();

    expect(await run(['generate']), 0);
    expect(out.toString(), contains('0 created, 0 updated, 2 unchanged'));
    expect(output.lastModifiedSync(), modified);
  });

  test(
    'check passes when up to date and fails otherwise without writing',
    () async {
      expect(await run(['check']), 1);
      expect(
        err.toString(),
        contains(
          'lib/graphql/a.graphql.dart: error[outdated-output]: Generated file is missing.',
        ),
      );
      expect(file('lib/graphql/a.graphql.dart').existsSync(), isFalse);

      await run(['generate']);
      expect(await run(['check']), 0);

      file('lib/graphql/a.graphql.dart').writeAsStringSync(
        '// GENERATED CODE - DO NOT MODIFY BY HAND.\n'
        '// Generated by gqlify from tampered',
      );
      expect(await run(['check']), 1);
      expect(
        err.toString(),
        contains(
          'a.graphql.dart: error[outdated-output]: Generated file is out of date.',
        ),
      );
    },
  );

  test('removes outputs of deleted documents', () async {
    write('lib/graphql/b.graphql', 'query B { products { name } }');
    await run(['generate']);
    expect(file('lib/graphql/b.graphql.dart').existsSync(), isTrue);

    file('lib/graphql/b.graphql').deleteSync();
    expect(await run(['check']), 1);
    expect(
      err.toString(),
      contains(
        'b.graphql.dart: error[outdated-output]: Generated file is stale',
      ),
    );
    expect(await run(['generate']), 0);
    expect(out.toString(), contains('1 removed'));
    expect(file('lib/graphql/b.graphql.dart').existsSync(), isFalse);
    expect(file('lib/graphql/a.graphql.dart').existsSync(), isTrue);
  });

  test('invalid documents fail without changing any file', () async {
    await run(['generate']);
    final before = file('lib/graphql/a.graphql.dart').readAsStringSync();
    write('lib/graphql/a.graphql', 'query A { products { nope } }');

    expect(await run(['generate']), 1);
    expect(
      err.toString(),
      contains('lib/graphql/a.graphql:1:22: error[unknown-field]'),
    );
    expect(file('lib/graphql/a.graphql.dart').readAsStringSync(), before);
  });

  test('never overwrites files it did not generate', () async {
    write('lib/graphql/a.graphql.dart', '// hand written');
    expect(await run(['generate']), 1);
    expect(err.toString(), contains('output-conflict'));
    expect(
      file('lib/graphql/a.graphql.dart').readAsStringSync(),
      '// hand written',
    );
  });

  test('ignores unrelated .graphql.dart files without the marker', () async {
    write('lib/other.graphql.dart', '// not ours');
    await run(['generate']);
    expect(file('lib/other.graphql.dart').existsSync(), isTrue);
  });

  test('reports configuration errors', () async {
    write('gqlify.yaml', 'schema: lib/graphql/schema.graphql\nmdoe: both\n');
    expect(await run(['generate']), 1);
    expect(err.toString(), contains('Unknown setting "mdoe"'));

    file('gqlify.yaml').deleteSync();
    expect(await run(['generate']), 1);
    expect(err.toString(), contains('missing-config'));
  });

  test('json reporter', () async {
    write('lib/graphql/a.graphql', 'query A { products { id nope } }');
    expect(await run(['--reporter', 'json', 'generate']), 1);
    final failed = jsonDecode(out.toString()) as Map<String, Object?>;
    expect(failed['success'], isFalse);
    expect(failed['diagnostics'], [
      {
        'severity': 'error',
        'code': 'unknown-field',
        'message': 'Cannot query field "nope" on type "Product".',
        'path': 'lib/graphql/a.graphql',
        'line': 1,
        'column': 25,
      },
    ]);
    expect(err.toString(), isEmpty);

    write('lib/graphql/a.graphql', 'query A { products { id } }');
    expect(await run(['--reporter', 'json', 'generate']), 0);
    final ok = jsonDecode(out.toString()) as Map<String, Object?>;
    expect(
      ok['files'],
      containsPair('created', [
        'lib/graphql/a.graphql.dart',
        'lib/graphql/schema.graphql.dart',
      ]),
    );
  });

  test('mode switches reconcile outputs', () async {
    write('lib/graphql/schema.graphql', '$_schema enum Status { ACTIVE }');
    await run(['generate']);
    write(
      'gqlify.yaml',
      'schema: lib/graphql/schema.graphql\nmode: schema_only\n',
    );
    expect(await run(['generate']), 0);
    expect(file('lib/graphql/a.graphql.dart').existsSync(), isFalse);
    final schemaOnly = file(
      'lib/graphql/schema.graphql.dart',
    ).readAsStringSync();
    expect(schemaOnly, isNot(contains('GqlifyClient')));
    expect(schemaOnly, contains('enum Status'));

    write('gqlify.yaml', 'schema: lib/graphql/schema.graphql\nmode: both\n');
    expect(await run(['generate']), 0);
    expect(file('lib/graphql/a.graphql.dart').existsSync(), isTrue);
    expect(await run(['check']), 0);
  });

  test('warnings do not fail generation', () async {
    write(
      'lib/graphql/schema.graphql',
      'type Product { id: ID! old: Int @deprecated } '
          'type Query { products: [Product!]! }',
    );
    write('lib/graphql/a.graphql', 'query A { products { id old } }');
    expect(await run(['generate']), 0);
    expect(err.toString(), contains('warning[deprecated-field]'));
  });

  test('usage errors', () async {
    expect(await run(['nope']), 64);
  });
}
