import 'package:path/path.dart' as p;

import '../ir/model.dart';
import 'naming.dart';

const _runtimeImport = "import 'package:gqlify_runtime/gqlify_runtime.dart';";
const _internalImport = "import 'package:gqlify_runtime/internal.dart';";

/// Renders unformatted Dart source for every library of [model], keyed by
/// output path. Formatting is applied by the caller.
Map<String, String> emitLibraries(GenerationModel model) => {
  if (model.documents.isNotEmpty)
    model.schemaOutputPath: _emitSchemaLibrary(model),
  for (final doc in model.documents)
    doc.outputPath: _emitDocumentLibrary(model, doc),
};

String _header(List<String> sources) => [
  '// GENERATED CODE - DO NOT MODIFY BY HAND.',
  '// Generated by gqlify from ${sources.join(', ')}.',
  '',
  '// ignore_for_file: type=lint, unused_import',
  '',
].join('\n');

String _emitSchemaLibrary(GenerationModel model) {
  final out = StringBuffer(_header(model.schemaSourcePaths))
    ..writeln(_runtimeImport)
    ..writeln()
    ..writeln(
      '/// Client for the GraphQL API described by '
      '${model.schemaSourcePaths.join(', ')}.',
    )
    ..writeln('///')
    ..writeln(
      '/// Operation methods are added by extensions declared in the '
      'generated document libraries; import those to call them.',
    )
    ..writeln('class ${model.clientName} extends GqlifyClientBase {')
    ..writeln('  ${model.clientName}({required super.transport});')
    ..writeln('}');
  return out.toString();
}

String _emitDocumentLibrary(GenerationModel model, DocumentLibrary doc) {
  final schemaImport = p.posix.relative(
    model.schemaOutputPath,
    from: p.posix.dirname(doc.outputPath),
  );
  final out = StringBuffer(_header([doc.sourcePath]))
    ..writeln(_runtimeImport)
    ..writeln(_internalImport)
    ..writeln()
    ..writeln("import '$schemaImport';")
    ..writeln();
  for (final op in doc.operations) {
    _OperationEmitter(out, model.clientName, op).emit();
  }
  return out.toString();
}

final class _OperationEmitter {
  _OperationEmitter(this.out, this.clientName, this.op);

  final StringBuffer out;
  final String clientName;
  final OperationModel op;

  String get _keyword => op.type.name;

  void emit() {
    out.writeln('const ${op.documentConstName} = ${dartString(op.document)};');
    out.writeln();
    _descriptor();
    _extension();
    final emitted = <SelectionClass>{};
    void visit(SelectionClass cls) {
      if (!emitted.add(cls)) return;
      _selectionClass(cls);
      for (final f in cls.fields) {
        if (_objectOf(f.type) case final child?) visit(child);
      }
    }

    visit(op.data);
  }

  void _descriptor() {
    final data = op.data.dartName;
    out
      ..writeln('/// The `$_keyword ${op.name}` operation.')
      ..writeln('///')
      ..writeln(
        '/// Prefer `$clientName.${op.methodName}`; use this class with '
        '`$clientName.execute` for full responses or request options.',
      )
      ..writeln(
        'final class ${op.descriptorName} extends GqlifyOperation<$data> {',
      );
    if (op.variables.isEmpty) {
      out.writeln('  const ${op.descriptorName}();');
    } else {
      out.writeln('  const ${op.descriptorName}({');
      for (final v in op.variables) {
        out.writeln(
          '    ${v.isRequired ? 'required ' : ''}this.${v.dartName},',
        );
      }
      out.writeln('  });');
    }
    out.writeln();
    for (final v in op.variables) {
      out
        ..writeln('  /// Variable `\$${v.graphqlName}`.')
        ..writeln('  final ${v.parameterType} ${v.dartName};')
        ..writeln();
    }
    out
      ..writeln('  @override')
      ..writeln("  String get operationName => '${op.name}';")
      ..writeln()
      ..writeln('  @override')
      ..writeln(
        '  GqlifyOperationType get operationType => '
        'GqlifyOperationType.$_keyword;',
      )
      ..writeln()
      ..writeln('  @override')
      ..writeln('  String get document => ${op.documentConstName};')
      ..writeln()
      ..writeln('  @override');
    if (op.variables.isEmpty) {
      out.writeln('  Map<String, Object?> get variables => const {};');
    } else {
      out.writeln('  Map<String, Object?> get variables => {');
      for (final v in op.variables) {
        // Optional variables are omitted when null so that server-side
        // defaults apply.
        final value = _encode(v.dartName, v.type, 0);
        if (v.isRequired) {
          out.writeln("    '${v.graphqlName}': $value,");
        } else {
          out.writeln(
            "    if (${v.dartName} != null) '${v.graphqlName}': $value,",
          );
        }
      }
      out.writeln('  };');
    }
    out
      ..writeln()
      ..writeln('  @override')
      ..writeln(
        '  $data parseData(Map<String, Object?> data) => '
        '$data.fromJson(data);',
      )
      ..writeln('}')
      ..writeln();
  }

  void _extension() {
    final data = op.data.dartName;
    final args = op.variables
        .map((v) => '${v.dartName}: ${v.dartName}')
        .join(', ');
    final construct = op.variables.isEmpty
        ? 'const ${op.descriptorName}()'
        : '${op.descriptorName}($args)';
    out
      ..writeln('extension ${op.extensionName} on $clientName {')
      ..writeln('  /// Executes `$_keyword ${op.name}` and returns its data.')
      ..writeln('  ///')
      ..writeln(
        '  /// Throws [GraphQLResponseException] if the response contains '
        'GraphQL errors, even alongside partial data.',
      )
      ..write('  Future<$data> ${op.methodName}(');
    if (op.variables.isNotEmpty) {
      out.write('{');
      for (final v in op.variables) {
        out.write(
          '${v.isRequired ? 'required ' : ''}${v.parameterType} ${v.dartName}, ',
        );
      }
      out.write('}');
    }
    out
      ..writeln(') async =>')
      ..writeln('      (await execute($construct)).dataOrThrow;')
      ..writeln('}')
      ..writeln();
  }

  void _selectionClass(SelectionClass cls) {
    final name = cls.dartName;
    final fields = cls.fields;
    out
      ..writeln('/// Selection on `${cls.graphqlType}`.')
      ..writeln('final class $name {');

    out.writeln('  const $name({');
    for (final f in fields) {
      out.writeln('    required this.${f.dartName},');
    }
    out.writeln('  });');
    out.writeln();

    out.writeln(
      '  factory $name.fromJson(Map<String, Object?> json) => $name(',
    );
    for (final f in fields) {
      out.writeln(
        '    ${f.dartName}: '
        '${_decode(_FieldReader(f.responseKey, name), f.type, 0)},',
      );
    }
    out.writeln('  );');
    out.writeln();

    for (final f in fields) {
      out.write(docComment(f.description, indent: '  '));
      if (f.deprecationReason != null) {
        out.writeln('  @Deprecated(${dartString(f.deprecationReason!)})');
      }
      out
        ..writeln('  final ${f.type.dartType} ${f.dartName};')
        ..writeln();
    }

    out.writeln('  Map<String, Object?> toJson() => {');
    for (final f in fields) {
      out.writeln("    '${f.responseKey}': ${_encode(f.dartName, f.type, 0)},");
    }
    out.writeln('  };');
    out.writeln();

    final comparisons = fields.map(
      (f) => f.type is ListValue
          ? 'gqlifyDeepEquals(other.${f.dartName}, ${f.dartName})'
          : 'other.${f.dartName} == ${f.dartName}',
    );
    out
      ..writeln('  @override')
      ..writeln('  bool operator ==(Object other) =>')
      ..writeln('      identical(this, other) ||')
      ..writeln(
        '      other is $name${comparisons.map((c) => ' && $c').join()};',
      )
      ..writeln();

    final hashed = fields
        .map(
          (f) => f.type is ListValue
              ? 'gqlifyDeepHash(${f.dartName})'
              : f.dartName,
        )
        .toList();
    final hash = switch (hashed.length) {
      0 => '0',
      1 => '${hashed.single}.hashCode',
      <= 20 => 'Object.hash(${hashed.join(', ')})',
      _ => 'Object.hashAll([${hashed.join(', ')}])',
    };
    out
      ..writeln('  @override')
      ..writeln('  int get hashCode => $hash;')
      ..writeln();

    final described = fields
        .map((f) => '${f.dartName.replaceAll(r'$', r'\$')}: \${${f.dartName}}')
        .join(', ');
    out
      ..writeln('  @override')
      ..writeln("  String toString() => '$name($described)';")
      ..writeln('}')
      ..writeln();
  }

  static SelectionClass? _objectOf(ValueType type) => switch (type) {
    ObjectValue(:final selection) => selection,
    ListValue(:final item) => _objectOf(item),
    ScalarValue() => null,
  };
}

/// Source of a JSON value being decoded: a map entry or a list element.
sealed class _Reader {
  /// Expression reading the raw JSON value as [rawType].
  String read(String rawType);

  /// Expression reading a Float as `double` / `double?`.
  String readDouble({required bool nullable});
}

final class _FieldReader extends _Reader {
  _FieldReader(this.key, this.owner);

  final String key;
  final String owner;

  String get _args => 'json, ${dartString(key)}, ${dartString(owner)}';

  @override
  String read(String rawType) => 'gqlifyRead<$rawType>($_args)';

  @override
  String readDouble({required bool nullable}) =>
      nullable ? 'gqlifyReadDoubleOrNull($_args)' : 'gqlifyReadDouble($_args)';
}

final class _ItemReader extends _Reader {
  _ItemReader(this.variable, this.location);

  final String variable;
  final String location;

  @override
  String read(String rawType) =>
      'gqlifyCast<$rawType>($variable, ${dartString(location)})';

  @override
  String readDouble({required bool nullable}) => nullable
      ? 'gqlifyCastDoubleOrNull($variable, ${dartString(location)})'
      : 'gqlifyCastDouble($variable, ${dartString(location)})';
}

String _location(_Reader reader) => switch (reader) {
  _FieldReader(:final owner, :final key) => '$owner.$key[]',
  _ItemReader(:final location) => '$location[]',
};

/// Expression decoding the value supplied by [reader] as [type].
String _decode(_Reader reader, ValueType type, int depth) {
  final q = type.nullable ? '?' : '';
  switch (type) {
    case ScalarValue():
      if (type.isFloat) return reader.readDouble(nullable: type.nullable);
      return reader.read('${type.baseDartType}$q');
    case ObjectValue(:final selection):
      final raw = reader.read('Map<String, Object?>$q');
      if (!type.nullable) return '${selection.dartName}.fromJson($raw)';
      final v = 'v$depth';
      return 'switch ($raw) { null => null, final $v => '
          '${selection.dartName}.fromJson($v) }';
    case ListValue(:final item):
      final raw = reader.read('List<Object?>$q');
      final e = 'e$depth';
      final element = _decode(
        _ItemReader(e, _location(reader)),
        item,
        depth + 1,
      );
      if (!type.nullable) return '[for (final $e in $raw) $element]';
      final v = 'v$depth';
      return 'switch ($raw) { null => null, final $v => '
          '[for (final $e in $v) $element] }';
  }
}

/// Expression encoding [expr] of [type] as JSON.
String _encode(String expr, ValueType type, int depth) {
  if (!type.containsObject) return expr;
  switch (type) {
    case ScalarValue():
      return expr;
    case ObjectValue():
      return type.nullable ? '$expr?.toJson()' : '$expr.toJson()';
    case ListValue(:final item):
      final e = 'e$depth';
      final element = _encode(e, item, depth + 1);
      if (!type.nullable) return '[for (final $e in $expr) $element]';
      final v = 'v$depth';
      return 'switch ($expr) { null => null, final $v => '
          '[for (final $e in $v) $element] }';
  }
}
