import 'package:path/path.dart' as p;

import '../config.dart';
import '../ir/model.dart';
import 'naming.dart';

/// Renders unformatted Dart source for every library of [model], keyed by
/// output path. Formatting is applied by the caller.
Map<String, String> emitLibraries(GenerationModel model) => {
  for (final library in model.libraries)
    library.outputPath: _LibraryEmitter(library).emit(),
};

final class _LibraryEmitter {
  _LibraryEmitter(this.library);

  final LibraryModel library;
  final out = StringBuffer();

  String emit() {
    _header();
    if (library.clientName case final client?) _client(client);
    library.enums.forEach(_enum);
    library.inputs.forEach(_input);
    library.operations.forEach(_operation);
    final selections = [...library.selections]
      ..sort((a, b) => a.group != b.group ? a.group - b.group : a.seq - b.seq);
    for (final selection in selections) {
      switch (selection) {
        case FragmentInterface():
          _interface(selection);
        case SealedSelection():
          _sealed(selection);
        case SelectionClass():
          _class(selection);
      }
    }
    return out.toString();
  }

  // ---------------------------------------------------------------------------
  // Header

  void _header() {
    out
      ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND.')
      ..writeln(
        '// Generated by gqlify from ${library.sourcePaths.join(', ')}.',
      )
      ..writeln()
      ..writeln(
        '// ignore_for_file: type=lint, unused_import, '
        'deprecated_member_use, deprecated_member_use_from_same_package',
      )
      ..writeln()
      ..writeln("import 'package:gqlify_runtime/gqlify_runtime.dart';")
      ..writeln("import 'package:gqlify_runtime/internal.dart';");
    final scalarImports = {
      for (final type in _valueTypes()) ?_scalarImport(type),
    }.toList()..sort();
    for (final uri in scalarImports) {
      out.writeln('import ${dartString(uri)};');
    }
    final relative = [
      for (final path in library.imports)
        if (path != library.outputPath)
          p.posix.relative(path, from: p.posix.dirname(library.outputPath)),
    ]..sort();
    if (relative.isNotEmpty) out.writeln();
    for (final uri in relative) {
      out.writeln('import ${dartString(uri)};');
    }
    out.writeln();
  }

  Iterable<ValueType> _valueTypes() sync* {
    for (final input in library.inputs) {
      for (final f in input.fields) {
        yield f.type;
      }
    }
    for (final op in library.operations) {
      for (final v in op.variables) {
        yield v.type;
      }
    }
    for (final selection in library.selections) {
      final fields = switch (selection) {
        SelectionClass(:final fields) => fields,
        SealedSelection(:final baseFields) => baseFields,
        FragmentInterface(:final fields) => fields,
      };
      for (final f in fields) {
        yield f.type;
      }
    }
  }

  static String? _scalarImport(ValueType type) => switch (type) {
    ScalarValue(:final mapping) => mapping.import,
    ListValue(:final item) => _scalarImport(item),
    _ => null,
  };

  // ---------------------------------------------------------------------------
  // Schema library

  void _client(String name) {
    out
      ..writeln(
        '/// Client for the GraphQL API described by '
        '${library.sourcePaths.join(', ')}.',
      )
      ..writeln('///')
      ..writeln(
        '/// Operation methods are added by extensions declared in the '
        'generated document libraries; import those to call them.',
      )
      ..writeln('class $name extends GqlifyClientBase {')
      ..writeln('  $name({required super.transport});')
      ..writeln('}')
      ..writeln();
  }

  void _enum(EnumModel model) {
    final name = model.dartName;
    out
      ..write(docComment(model.description ?? 'Enum `${model.graphqlName}`.'))
      ..writeln('enum $name {');
    for (final v in model.values) {
      out.write(docComment(v.description, indent: '  '));
      if (v.deprecationReason != null) {
        out.writeln('  @Deprecated(${dartString(v.deprecationReason!)})');
      }
      out.writeln('  ${v.dartName}(${dartString(v.graphqlName)}),');
    }
    out
      ..writeln(
        '  /// A value unknown to this client, e.g. one added to the '
        'schema after the code was generated. It cannot be sent to the server.',
      )
      ..writeln("  \$unknown('');")
      ..writeln()
      ..writeln('  const $name(this.value);')
      ..writeln()
      ..writeln(
        '  /// Decodes a GraphQL enum value; unknown values become '
        '[\$unknown].',
      )
      ..writeln('  factory $name.fromJson(String json) => switch (json) {');
    for (final v in model.values) {
      out.writeln('    ${dartString(v.graphqlName)} => ${v.dartName},');
    }
    out
      ..writeln('    _ => \$unknown,')
      ..writeln('  };')
      ..writeln()
      ..writeln('  /// The GraphQL name of this value.')
      ..writeln('  final String value;')
      ..writeln()
      ..writeln('  /// The GraphQL name of this value; throws for [\$unknown].')
      ..writeln('  String toJson() => switch (this) {')
      ..writeln(
        '    \$unknown => throw UnsupportedError('
        "${dartString('Cannot encode an unknown value of enum ${model.graphqlName}.')}),",
      )
      ..writeln('    _ => value,')
      ..writeln('  };')
      ..writeln('}')
      ..writeln();
  }

  void _input(InputModel model) {
    final name = model.dartName;
    final fields = model.fields;
    out
      ..write(docComment(model.description ?? 'Input `${model.graphqlName}`.'))
      ..writeln('final class $name {');

    if (model.isOneOf) {
      // @oneOf: exactly one field is set, chosen by named constructor.
      for (final f in fields) {
        final others = [
          for (final o in fields)
            if (o != f) '${o.dartName} = null',
        ];
        out
          ..write(docComment(f.description, indent: '  '))
          ..writeln(
            '  const $name.${f.dartName}(${f.type.baseDartType} this.${f.dartName})'
            '${others.isEmpty ? '' : ' : ${others.join(', ')}'};',
          )
          ..writeln();
      }
      for (final f in fields) {
        out.writeln('  final ${f.type.asNullable().dartType} ${f.dartName};');
      }
      out
        ..writeln()
        ..writeln('  Map<String, Object?> toJson() => {');
      for (final f in fields) {
        out.writeln(
          '    if (${f.dartName} case final v?) '
          '${dartString(f.graphqlName)}: ${_encode('v', f.type.nonNullable, 0)},',
        );
      }
      out
        ..writeln('  };')
        ..writeln();
      _valueMembers(name, [for (final f in fields) (f.dartName, f.type)]);
      out
        ..writeln('}')
        ..writeln();
      return;
    }

    final nullable = [
      for (final f in fields)
        if (f.acceptsNull) f,
    ];
    _fieldsConstructor(name, fields, withNulls: nullable.isNotEmpty);
    for (final f in fields) {
      out.write(docComment(f.description, indent: '  '));
      if (f.deprecationReason != null) {
        out.writeln('  @Deprecated(${dartString(f.deprecationReason!)})');
      }
      out
        ..writeln('  final ${f.parameterType} ${f.dartName};')
        ..writeln();
    }
    if (nullable.isNotEmpty) _withNull(name, fields, nullable);
    out.writeln('  Map<String, Object?> toJson() => {');
    _encodeFields(fields);
    out
      ..writeln('  };')
      ..writeln();
    _valueMembers(name, [
      for (final f in fields) (f.dartName, f.type),
      if (nullable.isNotEmpty) ('_nulls', null),
    ]);
    out
      ..writeln('}')
      ..writeln();
  }

  /// Constructor taking every field; optional fields default to omitted.
  void _fieldsConstructor(
    String name,
    List<InputFieldModel> fields, {
    required bool withNulls,
  }) {
    final init = withNulls ? ' : _nulls = const {}' : '';
    if (fields.isEmpty) {
      out.writeln('  const $name()$init;');
    } else {
      out.writeln('  const $name({');
      for (final f in fields) {
        out.writeln(
          '    ${f.isRequired ? 'required ' : ''}this.${f.dartName},',
        );
      }
      out.writeln('  })$init;');
    }
    out.writeln();
    if (withNulls) {
      out
        ..writeln('  const $name._(')
        ..writeln(
          [
            for (final f in fields) '    this.${f.dartName},',
            '    this._nulls,',
          ].join('\n'),
        )
        ..writeln('  );')
        ..writeln()
        ..writeln('  /// GraphQL names of fields sent as explicit `null`.')
        ..writeln('  final Set<String> _nulls;')
        ..writeln();
    }
  }

  /// `withNull`: a copy that sends the flagged fields as explicit `null`.
  void _withNull(
    String name,
    List<InputFieldModel> fields,
    List<InputFieldModel> nullable,
  ) {
    out
      ..writeln(
        '  /// Returns a copy that sends the flagged fields as an '
        'explicit `null` instead of omitting them.',
      )
      ..writeln('  $name withNull({')
      ..writeln(
        [
          for (final f in nullable) '    bool ${f.dartName} = false,',
        ].join('\n'),
      )
      ..writeln('  }) => $name._(');
    for (final f in fields) {
      out.writeln(
        f.acceptsNull
            ? '    ${f.dartName} ? null : this.${f.dartName},'
            : '    this.${f.dartName},',
      );
    }
    final flagged = [
      for (final f in nullable)
        'if (${f.dartName}) ${dartString(f.graphqlName)}',
    ];
    out
      ..writeln('    {..._nulls, ${flagged.join(', ')}},')
      ..writeln('  );')
      ..writeln();
  }

  /// Map entries encoding [fields]; omitted when `null` unless flagged.
  void _encodeFields(List<InputFieldModel> fields) {
    for (final f in fields) {
      final key = dartString(f.graphqlName);
      if (f.isRequired) {
        out.writeln('    $key: ${_encode(f.dartName, f.type, 0)},');
      } else {
        final explicitNull = f.acceptsNull
            ? ' else if (_nulls.contains($key)) $key: null'
            : '';
        out.writeln(
          '    if (${f.dartName} case final v?) '
          '$key: ${_encode('v', f.type.nonNullable, 0)}$explicitNull,',
        );
      }
    }
  }

  // ---------------------------------------------------------------------------
  // Operations

  void _operation(OperationModel op) {
    final keyword = op.type.name;
    final data = op.dataName;
    final nullable = [
      for (final v in op.variables)
        if (v.acceptsNull) v,
    ];

    out
      ..writeln('const ${op.documentConstName} = ${dartString(op.document)};')
      ..writeln()
      ..writeln('/// The `$keyword ${op.name}` operation.')
      ..writeln('///')
      ..writeln(
        '/// Prefer `${op.clientName}.${op.methodName}`; use this class '
        'with `${op.clientName}.execute` for full responses, request options '
        'or explicit `null` variables.',
      )
      ..writeln(
        'final class ${op.descriptorName} extends GqlifyOperation<$data> {',
      );
    _fieldsConstructor(
      op.descriptorName,
      op.variables,
      withNulls: nullable.isNotEmpty,
    );
    for (final v in op.variables) {
      out
        ..writeln('  /// Variable `\$${v.graphqlName}`.')
        ..writeln('  final ${v.parameterType} ${v.dartName};')
        ..writeln();
    }
    if (nullable.isNotEmpty) {
      _withNull(op.descriptorName, op.variables, nullable);
    }
    out
      ..writeln('  @override')
      ..writeln('  String get operationName => ${dartString(op.name)};')
      ..writeln()
      ..writeln('  @override')
      ..writeln(
        '  GqlifyOperationType get operationType => '
        'GqlifyOperationType.$keyword;',
      )
      ..writeln()
      ..writeln('  @override')
      ..writeln('  String get document => ${op.documentConstName};')
      ..writeln()
      ..writeln('  @override')
      ..writeln('  Map<String, Object?> get variables => {');
    _encodeFields(op.variables);
    out
      ..writeln('  };')
      ..writeln()
      ..writeln('  @override')
      ..writeln(
        '  $data parseData(Map<String, Object?> data) => '
        '$data.fromJson(data);',
      )
      ..writeln()
      ..writeln('  @override')
      ..writeln('  bool operator ==(Object other) =>')
      ..writeln(
        '      other is ${op.descriptorName} && '
        'gqlifyDeepEquals(other.variables, variables);',
      )
      ..writeln()
      ..writeln('  @override')
      ..writeln('  int get hashCode => gqlifyDeepHash(variables);')
      ..writeln('}')
      ..writeln();

    final args = op.variables
        .map((v) => '${v.dartName}: ${v.dartName}')
        .join(', ');
    final construct = op.variables.isEmpty
        ? 'const ${op.descriptorName}()'
        : '${op.descriptorName}($args)';
    out
      ..writeln('extension ${op.extensionName} on ${op.clientName} {')
      ..writeln('  /// Executes `$keyword ${op.name}` and returns its data.')
      ..writeln('  ///')
      ..writeln(
        '  /// Throws [GraphQLResponseException] if the response contains '
        'GraphQL errors, even alongside partial data.',
      )
      ..write('  Future<$data> ${op.methodName}(');
    if (op.variables.isNotEmpty) {
      out.write('{');
      for (final v in op.variables) {
        out.write(
          '${v.isRequired ? 'required ' : ''}${v.parameterType} ${v.dartName}, ',
        );
      }
      out.write('}');
    }
    out
      ..writeln(') async =>')
      ..writeln('      (await execute($construct)).dataOrThrow;')
      ..writeln('}')
      ..writeln();
  }

  // ---------------------------------------------------------------------------
  // Selections

  void _interface(FragmentInterface model) {
    out
      ..write(
        docComment(model.description ?? 'Selection on `${model.graphqlType}`.'),
      )
      ..writeln(
        'abstract interface class ${model.dartName}'
        '${_implementsClause(model.implements)} {',
      );
    for (final f in model.fields) {
      _fieldDoc(f);
      out
        ..writeln('  ${f.type.dartType} get ${f.dartName};')
        ..writeln();
    }
    out
      ..writeln('  Map<String, Object?> toJson();')
      ..writeln('}')
      ..writeln();
  }

  void _sealed(SealedSelection model) {
    final name = model.dartName;
    out
      ..writeln(
        '/// Selection on `${model.graphqlType}`, decoded by '
        '`__typename`. Switch over the subclasses to handle each type.',
      )
      ..writeln('sealed class $name${_implementsClause(model.implements)} {')
      ..writeln('  const $name();')
      ..writeln()
      ..writeln('  factory $name.fromJson(Map<String, Object?> json) =>')
      ..writeln(
        '      switch (gqlifyRead<String>(json, '
        "'__typename', ${dartString(name)})) {",
      );
    for (final MapEntry(key: type, value: variant) in model.variants.entries) {
      out.writeln(
        '        ${dartString(type)} => ${variant.dartName}.fromJson(json),',
      );
    }
    out
      ..writeln('        _ => ${model.other.dartName}.fromJson(json),')
      ..writeln('      };')
      ..writeln();
    for (final f in model.baseFields) {
      _fieldDoc(f);
      out
        ..writeln('  ${f.type.dartType} get ${f.dartName};')
        ..writeln();
    }
    out
      ..writeln('  Map<String, Object?> toJson();')
      ..writeln('}')
      ..writeln();
  }

  void _class(SelectionClass cls) {
    final name = cls.dartName;
    final fields = cls.fields;
    final superclass = cls.superclass;
    final String doc;
    if (superclass == null) {
      doc = '/// Selection on `${cls.graphqlType}`.';
    } else if (name.endsWith(r'$Other')) {
      doc =
          '/// [$superclass] for any type without a dedicated subclass, '
          'including types added to the schema after generation.';
    } else {
      doc = '/// [$superclass] when the runtime type is `${cls.graphqlType}`.';
    }
    final extendsClause = superclass == null ? '' : ' extends $superclass';
    out
      ..writeln(doc)
      ..writeln(
        'final class $name$extendsClause${_implementsClause(cls.implements)} {',
      );

    if (fields.isEmpty) {
      out.writeln('  const $name();');
    } else {
      out.writeln('  const $name({');
      for (final f in fields) {
        out.writeln('    required this.${f.dartName},');
      }
      out.writeln('  });');
    }
    out
      ..writeln()
      ..writeln(
        '  factory $name.fromJson(Map<String, Object?> json) => $name(',
      );
    for (final f in fields) {
      out.writeln(
        '    ${f.dartName}: '
        '${_decode(_FieldReader(f.responseKey, name), f.type, 0)},',
      );
    }
    out
      ..writeln('  );')
      ..writeln();

    for (final f in fields) {
      _fieldDoc(f);
      out
        ..writeln('  final ${f.type.dartType} ${f.dartName};')
        ..writeln();
    }

    out.writeln('  Map<String, Object?> toJson() => {');
    for (final f in fields) {
      out.writeln(
        '    ${dartString(f.responseKey)}: ${_encode(f.dartName, f.type, 0)},',
      );
    }
    out
      ..writeln('  };')
      ..writeln();
    _valueMembers(name, [for (final f in fields) (f.dartName, f.type)]);
    out
      ..writeln('}')
      ..writeln();
  }

  void _fieldDoc(FieldModel f) {
    out.write(docComment(f.description, indent: '  '));
    if (f.deprecationReason != null) {
      out.writeln('  @Deprecated(${dartString(f.deprecationReason!)})');
    }
  }

  static String _implementsClause(List<String> names) =>
      names.isEmpty ? '' : ' implements ${names.join(', ')}';

  /// `==`, `hashCode` and `toString` over [members] (name, type); a `null`
  /// type marks the private `_nulls` set.
  void _valueMembers(String name, List<(String, ValueType?)> members) {
    bool deep((String, ValueType?) m) => m.$2 == null || m.$2 is ListValue;
    final comparisons = members.map(
      (m) => deep(m)
          ? 'gqlifyDeepEquals(other.${m.$1}, ${m.$1})'
          : 'other.${m.$1} == ${m.$1}',
    );
    out
      ..writeln('  @override')
      ..writeln('  bool operator ==(Object other) =>')
      ..writeln('      identical(this, other) ||')
      ..writeln(
        '      other is $name${comparisons.map((c) => ' && $c').join()};',
      )
      ..writeln();

    final hashed = [
      for (final m in members) deep(m) ? 'gqlifyDeepHash(${m.$1})' : m.$1,
    ];
    final hash = switch (hashed.length) {
      0 => '${dartString(name)}.hashCode',
      1 when deep(members.single) => hashed.single,
      1 => '${hashed.single}.hashCode',
      <= 20 => 'Object.hash(${hashed.join(', ')})',
      _ => 'Object.hashAll([${hashed.join(', ')}])',
    };
    out
      ..writeln('  @override')
      ..writeln('  int get hashCode => $hash;')
      ..writeln();

    final described = [
      for (final m in members)
        if (m.$2 != null) '${m.$1.replaceAll(r'$', r'\$')}: \${${m.$1}}',
    ].join(', ');
    out
      ..writeln('  @override')
      ..writeln(
        "  String toString() => '${name.replaceAll(r'$', r'\$')}($described)';",
      );
  }
}

// -----------------------------------------------------------------------------
// Codecs

/// Source of a JSON value being decoded: a map entry or a list element.
sealed class _Reader {
  /// Expression reading the raw JSON value as [rawType].
  String read(String rawType);
}

final class _FieldReader extends _Reader {
  _FieldReader(this.key, this.owner);

  final String key;
  final String owner;

  @override
  String read(String rawType) =>
      'gqlifyRead<$rawType>(json, ${dartString(key)}, ${dartString(owner)})';
}

final class _ItemReader extends _Reader {
  _ItemReader(this.variable, this.location);

  final String variable;
  final String location;

  @override
  String read(String rawType) =>
      'gqlifyCast<$rawType>($variable, ${dartString(location)})';
}

String _location(_Reader reader) => switch (reader) {
  _FieldReader(:final owner, :final key) => '$owner.$key[]',
  _ItemReader(:final location) => '$location[]',
};

/// Expression decoding the value supplied by [reader] as [type].
String _decode(_Reader reader, ValueType type, int depth) {
  final String readType;
  final String Function(String raw) convert;
  switch (type) {
    case ScalarValue(:final mapping):
      readType = mapping.jsonType.readType;
      final toDouble = mapping.jsonType == ScalarJsonType.double_;
      final fromJson = mapping.fromJson;
      if (!toDouble && fromJson == null) {
        return reader.read('$readType${type.nullable ? '?' : ''}');
      }
      convert = (raw) {
        final value = toDouble ? '$raw.toDouble()' : raw;
        return fromJson == null ? value : '$fromJson($value)';
      };
    case EnumValue(:final model):
      readType = 'String';
      convert = (raw) => '${model.dartName}.fromJson($raw)';
    case ObjectValue(:final dartName):
      readType = 'Map<String, Object?>';
      convert = (raw) => '$dartName.fromJson($raw)';
    case ListValue(:final item):
      readType = 'List<Object?>';
      final e = 'e$depth';
      final element = _decode(
        _ItemReader(e, _location(reader)),
        item,
        depth + 1,
      );
      convert = (raw) => '[for (final $e in $raw) $element]';
    case InputObjectValue():
      throw StateError('Input objects are never decoded');
  }
  if (!type.nullable) return convert(reader.read(readType));
  final v = 'v$depth';
  return 'switch (${reader.read('$readType?')}) '
      '{ null => null, final $v => ${convert(v)} }';
}

/// Expression encoding [expr] of [type] as JSON.
String _encode(String expr, ValueType type, int depth) {
  if (!type.needsEncoding) return expr;
  String convert(String value) => switch (type) {
    ScalarValue(:final mapping) => '${mapping.toJson}($value)',
    EnumValue() || InputObjectValue() || ObjectValue() => '$value.toJson()',
    ListValue(:final item) =>
      '[for (final e$depth in $value) ${_encode('e$depth', item, depth + 1)}]',
  };
  if (!type.nullable) return convert(expr);
  if (type is EnumValue || type is InputObjectValue || type is ObjectValue) {
    return '$expr?.toJson()';
  }
  final v = 'v$depth';
  return 'switch ($expr) { null => null, final $v => ${convert(v)} }';
}

extension on ValueType {
  ValueType get nonNullable => switch (this) {
    ScalarValue(:final graphqlType, :final mapping) => ScalarValue(
      graphqlType,
      mapping,
      nullable: false,
    ),
    EnumValue(:final model) => EnumValue(model, nullable: false),
    InputObjectValue(:final model) => InputObjectValue(model, nullable: false),
    ObjectValue(:final dartName) => ObjectValue(dartName, nullable: false),
    ListValue(:final item) => ListValue(item, nullable: false),
  };
}
