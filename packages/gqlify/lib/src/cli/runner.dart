import 'dart:io';

import 'package:args/args.dart';
import 'package:args/command_runner.dart';
import 'package:path/path.dart' as p;

import '../diagnostics.dart';
import '../engine.dart';
import 'output_sync.dart';
import 'project.dart';

/// Exit codes of the `gqlify` command.
abstract final class ExitCodes {
  static const success = 0;

  /// Invalid schema/documents/config, or (for `check`) out-of-date outputs.
  static const failure = 1;
  static const usage = 64;
}

/// The `gqlify` command line interface.
final class GqlifyCommandRunner extends CommandRunner<int> {
  GqlifyCommandRunner({StringSink? out, StringSink? err})
    : out = out ?? stdout,
      err = err ?? stderr,
      super('gqlify', 'GraphQL, simplified for Dart.') {
    argParser.addOption(
      'project-dir',
      abbr: 'C',
      help:
          'Package root containing gqlify.yaml (defaults to the current '
          'directory).',
    );
    addCommand(_GenerateCommand(this));
    addCommand(_CheckCommand(this));
  }

  final StringSink out;
  final StringSink err;

  @override
  Future<int> run(Iterable<String> args) async {
    try {
      return await super.run(args) ?? ExitCodes.success;
    } on UsageException catch (e) {
      err.writeln(e);
      return ExitCodes.usage;
    }
  }

  Project project(ArgResults? globalResults) => Project(
    p.normalize(
      p.absolute(
        globalResults?.option('project-dir') ?? Directory.current.path,
      ),
    ),
  );
}

abstract base class _GqlifyCommand extends Command<int> {
  _GqlifyCommand(this.cli);

  final GqlifyCommandRunner cli;

  /// Loads the project and runs the engine; prints diagnostics.
  (Project, GenerationResult)? generateInMemory() {
    final project = cli.project(globalResults);
    final sink = DiagnosticSink();
    final config = project.loadConfig(sink);
    final input = config == null ? null : project.loadInput(config, sink);
    if (input == null) {
      _print(sink.sorted());
      return null;
    }
    final result = GqlifyEngine().generate(input);
    _print(result.diagnostics);
    return (project, result);
  }

  void _print(List<Diagnostic> diagnostics) {
    for (final d in diagnostics) {
      cli.err.writeln(d);
    }
  }
}

final class _GenerateCommand extends _GqlifyCommand {
  _GenerateCommand(super.cli);

  @override
  String get name => 'generate';

  @override
  String get description =>
      'Generate Dart code from the schema and operation documents.';

  @override
  Future<int> run() async {
    final stopwatch = Stopwatch()..start();
    final generated = generateInMemory();
    if (generated == null) return ExitCodes.failure;
    final (project, result) = generated;
    if (result.hasErrors) {
      cli.err.writeln('gqlify: generation failed; no files were changed.');
      return ExitCodes.failure;
    }
    final plan = OutputPlan.compute(project, result.outputs);
    if (plan.conflicts.isNotEmpty) {
      for (final path in plan.conflicts) {
        cli.err.writeln(
          '$path: error[output-conflict]: File exists and was not '
          'generated by gqlify; refusing to overwrite it.',
        );
      }
      return ExitCodes.failure;
    }
    plan.apply(project, result.outputs);
    cli.out.writeln(
      'gqlify: ${plan.created.length} created, ${plan.changed.length} updated, '
      '${plan.unchanged.length} unchanged, ${plan.stale.length} removed '
      '(${stopwatch.elapsedMilliseconds} ms).',
    );
    return ExitCodes.success;
  }
}

final class _CheckCommand extends _GqlifyCommand {
  _CheckCommand(super.cli);

  @override
  String get name => 'check';

  @override
  String get description =>
      'Validate schema and documents and verify generated files are up to '
      'date, without writing anything. Exits with 1 on failure (for CI).';

  @override
  Future<int> run() async {
    final generated = generateInMemory();
    if (generated == null) return ExitCodes.failure;
    final (project, result) = generated;
    if (result.hasErrors) return ExitCodes.failure;
    final plan = OutputPlan.compute(project, result.outputs);
    for (final (label, paths) in [
      ('missing', plan.created),
      ('out of date', plan.changed),
      ('stale (no longer generated)', plan.stale),
      ('conflicts with a non-generated file', plan.conflicts),
    ]) {
      for (final path in paths) {
        cli.err.writeln('$path: $label');
      }
    }
    if (!plan.isUpToDate) {
      cli.err.writeln(
        "gqlify: generated files are not up to date; run 'dart run gqlify generate'.",
      );
      return ExitCodes.failure;
    }
    cli.out.writeln(
      'gqlify: ${result.outputs.length} generated files are up to date.',
    );
    return ExitCodes.success;
  }
}
