/// Exit codes of the `gqlify` command.
abstract final class ExitCodes {
  static const success = 0;

  /// Invalid schema/documents/config, or (for `check`) out-of-date outputs.
  static const failure = 1;
  static const usage = 64;
}

/// The `gqlify` command line interface.
final class GqlifyCommandRunner extends CommandRunner<int> {
  GqlifyCommandRunner({StringSink? out, StringSink? err})
    : out = out ?? stdout,
      err = err ?? stderr,
      super('gqlify', 'GraphQL, simplified for Dart.') {
    argParser.addOption(
      'project-dir',
      abbr: 'C',
      help:
          'Package root containing gqlify.yaml (defaults to the current '
          'directory).',
    );
    argParser.addOption(
      'reporter',
      allowed: ['human', 'json'],
      defaultsTo: 'human',
      help:
          'Output format. "json" prints one machine-readable object to stdout.',
    );
    addCommand(_GenerateCommand(this));
    addCommand(_CheckCommand(this));
  }

  final StringSink out;
  final StringSink err;

  @override
  Future<int> run(Iterable<String> args) async {
    try {
      return await super.run(args) ?? ExitCodes.success;
    } on UsageException catch (e) {
      err.writeln(e);
      return ExitCodes.usage;
    }
  }

  Project project(ArgResults? globalResults) => Project(
    p.normalize(
      p.absolute(
        globalResults?.option('project-dir') ?? Directory.current.path,
      ),
    ),
  );
}

/// What a command did, rendered for humans (stderr/stdout) or as one JSON
/// object on stdout (`--reporter json`).
final class _Report {
  _Report(this.command);

  final String command;
  final stopwatch = Stopwatch()..start();
  final List<Diagnostic> diagnostics = [];
  final Map<String, List<String>> files = {};
  String? summary;
  bool success = false;

  Map<String, Object?> toJson() => {
    'command': command,
    'success': success,
    'diagnostics': [for (final d in diagnostics) d.toJson()],
    'files': files,
    'elapsedMs': stopwatch.elapsedMilliseconds,
  };
}

abstract base class _GqlifyCommand extends Command<int> {
  _GqlifyCommand(this.cli);

  final GqlifyCommandRunner cli;

  bool get _json => globalResults?.option('reporter') == 'json';

  /// Loads the project and runs the engine.
  (Project, GenerationResult)? generateInMemory(_Report report) {
    final project = cli.project(globalResults);
    final sink = DiagnosticSink();
    final config = project.loadConfig(sink);
    final input = config == null ? null : project.loadInput(config, sink);
    if (input == null) {
      report.diagnostics.addAll(sink.sorted());
      return null;
    }
    final result = GqlifyEngine().generate(input);
    report.diagnostics.addAll(result.diagnostics);
    return (project, result);
  }

  int finish(_Report report, {required bool success}) {
    report.success = success;
    if (_json) {
      cli.out.writeln(
        const JsonEncoder.withIndent('  ').convert(report.toJson()),
      );
    } else {
      for (final d in report.diagnostics) {
        cli.err.writeln(d);
      }
      if (report.summary case final summary?) {
        (success ? cli.out : cli.err).writeln(summary);
      }
    }
    return success ? ExitCodes.success : ExitCodes.failure;
  }
}

final class _GenerateCommand extends _GqlifyCommand {
  _GenerateCommand(super.cli);

  @override
  String get name => 'generate';

  @override
  String get description =>
      'Generate Dart code from the schema and operation documents.';

  @override
  Future<int> run() async {
    final report = _Report(name);
    final generated = generateInMemory(report);
    if (generated == null) return finish(report, success: false);
    final (project, result) = generated;
    if (result.hasErrors) {
      report.summary = 'gqlify: generation failed; no files were changed.';
      return finish(report, success: false);
    }
    final plan = OutputPlan.compute(project, result.outputs);
    if (plan.conflicts.isNotEmpty) {
      for (final path in plan.conflicts) {
        report.diagnostics.add(
          Diagnostic(
            severity: Severity.error,
            code: 'output-conflict',
            message:
                'File exists and was not generated by gqlify; refusing to '
                'overwrite it.',
            path: path,
          ),
        );
      }
      report.files['conflicts'] = plan.conflicts;
      report.summary = 'gqlify: generation failed; no files were changed.';
      return finish(report, success: false);
    }
    plan.apply(project, result.outputs);
    report.files.addAll({
      'created': plan.created,
      'updated': plan.changed,
      'unchanged': plan.unchanged,
      'removed': plan.stale,
    });
    report.summary =
        'gqlify: ${plan.created.length} created, ${plan.changed.length} updated, '
        '${plan.unchanged.length} unchanged, ${plan.stale.length} removed '
        '(${report.stopwatch.elapsedMilliseconds} ms).';
    return finish(report, success: true);
  }
}

final class _CheckCommand extends _GqlifyCommand {
  _CheckCommand(super.cli);

  @override
  String get name => 'check';

  @override
  String get description =>
      'Validate schema and documents and verify generated files are up to '
      'date, without writing anything. Exits with 1 on failure (for CI).';

  @override
  Future<int> run() async {
    final report = _Report(name);
    final generated = generateInMemory(report);
    if (generated == null) return finish(report, success: false);
    final (project, result) = generated;
    if (result.hasErrors) return finish(report, success: false);
    final plan = OutputPlan.compute(project, result.outputs);
    report.files.addAll({
      'missing': plan.created,
      'outdated': plan.changed,
      'upToDate': plan.unchanged,
      'stale': plan.stale,
      'conflicts': plan.conflicts,
    });
    for (final (label, paths) in [
      ('missing', plan.created),
      ('out of date', plan.changed),
      ('stale (no longer generated)', plan.stale),
      ('conflicts with a non-generated file', plan.conflicts),
    ]) {
      for (final path in paths) {
        report.diagnostics.add(
          Diagnostic(
            severity: Severity.error,
            code: 'outdated-output',
            message: 'Generated file is $label.',
            path: path,
          ),
        );
      }
    }
    if (!plan.isUpToDate) {
      report.summary =
          "gqlify: generated files are not up to date; run 'dart run gqlify generate'.";
      return finish(report, success: false);
    }
    report.summary =
        'gqlify: ${result.outputs.length} generated files are up to date.';
    return finish(report, success: true);
  }
}
