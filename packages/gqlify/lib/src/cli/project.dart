import 'dart:io';

import 'package:glob/glob.dart';
import 'package:glob/list_local_fs.dart';
import 'package:path/path.dart' as p;

import '../config.dart' hide resolveConfig;
import '../config.dart' as config_lib show resolveConfig;
import '../diagnostics.dart';
import '../emit/formatter.dart';
import '../engine.dart';
import '../source.dart';
import 'output_sync.dart' show tempSuffix;

/// First lines of every library gqlify generates. Files are only ever
/// overwritten or deleted by the CLI if they start with this marker.
const generatedMarker =
    '// GENERATED CODE - DO NOT MODIFY BY HAND.\n// Generated by gqlify from ';

/// File name suffixes of generated libraries.
const generatedSuffixes = ['.graphql.dart', '.gql.dart', '.json.dart'];

/// A package using gqlify, as seen by the CLI.
final class Project {
  Project(this.root);

  /// Absolute package root (the directory containing `gqlify.yaml`).
  final String root;

  String absolute(String relative) => p.joinAll([root, ...relative.split('/')]);

  /// Project-relative posix path of [absolutePath].
  String relative(String absolutePath) =>
      normalizePath(p.relative(absolutePath, from: root));

  /// Resolves the configuration from `gqlify.yaml` or `pubspec.yaml`.
  ResolvedConfig? resolveConfig(DiagnosticSink sink) =>
      config_lib.resolveConfig(
        gqlifyYaml: _readOptional(GqlifyConfig.fileName),
        pubspecYaml: _readOptional('pubspec.yaml'),
        sink: sink,
      );

  /// Reads the configuration; problems are reported to [sink].
  GqlifyConfig? loadConfig(DiagnosticSink sink) => resolveConfig(sink)?.config;

  /// Reads the schema and discovers and reads operation documents.
  GenerationInput? loadInput(GqlifyConfig config, DiagnosticSink sink) {
    final schema = <GqlifySource>[];
    for (final path in config.schema) {
      final file = File(absolute(path));
      if (!file.existsSync()) {
        sink.error(
          'missing-schema',
          'Schema file "$path" does not exist.',
          path: GqlifyConfig.fileName,
        );
        continue;
      }
      schema.add(GqlifySource(path, file.readAsStringSync()));
    }
    if (sink.hasErrors) return null;

    final documents = <GqlifySource>[];
    if (config.mode.includesOperations) {
      final schemaPaths = config.schema.toSet();
      for (final path in _discover(config.documents)) {
        if (schemaPaths.contains(path)) continue;
        documents.add(
          GqlifySource(path, File(absolute(path)).readAsStringSync()),
        );
      }
    }
    return GenerationInput(
      config: config,
      schema: schema,
      documents: documents,
      format: FormatSettings.fromProjectFiles(
        pubspecYaml: _readOptional('pubspec.yaml'),
        analysisOptionsYaml: _readOptional('analysis_options.yaml'),
      ),
    );
  }

  String? _readOptional(String relative) {
    final file = File(absolute(relative));
    return file.existsSync() ? file.readAsStringSync() : null;
  }

  /// Project-relative posix paths matching [patterns], sorted.
  List<String> _discover(List<String> patterns) {
    final paths = <String>{};
    for (final pattern in patterns) {
      final glob = Glob(pattern);
      for (final entity in glob.listSync(root: root, followLinks: false)) {
        if (entity is! File) continue;
        final relative = normalizePath(p.relative(entity.path, from: root));
        if (_isIgnored(relative)) continue;
        paths.add(relative);
      }
    }
    return paths.toList()..sort();
  }

  /// Whether [relative] is a hidden file or lies in `build/`, `.dart_tool/` or
  /// another hidden directory.
  static bool _isIgnored(String relative) =>
      _inIgnoredDirectory(relative) ||
      p.posix.basename(relative).startsWith('.');

  static bool _inIgnoredDirectory(String relative) {
    if (relative.startsWith('.dart_tool/') || relative.startsWith('build/')) {
      return true;
    }
    final segments = relative.split('/');
    return segments
        .take(segments.length - 1)
        .any((s) => s.startsWith('.') && s != '.' && s != '..');
  }

  /// Project-relative paths of existing files generated by gqlify.
  ///
  /// Ownership is decided by file name and [generatedMarker], never by a
  /// cache, so stale outputs are found even after the cache was deleted.
  ///
  /// Temporary files left behind by an interrupted run are deleted, so call
  /// this only while holding the project lock.
  List<String> ownedOutputs() {
    final owned = <String>[];
    final dir = Directory(root);
    for (final entity in dir.listSync(recursive: true, followLinks: false)) {
      if (entity is! File) continue;
      final relative = normalizePath(p.relative(entity.path, from: root));
      if (_inIgnoredDirectory(relative)) continue;
      final name = p.posix.basename(relative);
      if (name.startsWith('.') && name.endsWith(tempSuffix)) {
        try {
          entity.deleteSync();
        } on FileSystemException {
          // Best effort; it is ignored either way.
        }
        continue;
      }
      if (!generatedSuffixes.any(relative.endsWith)) continue;
      if (isGenerated(entity)) owned.add(relative);
    }
    return owned..sort();
  }

  static bool isGenerated(File file) {
    try {
      final handle = file.openSync();
      try {
        final bytes = handle.readSync(generatedMarker.length);
        return String.fromCharCodes(bytes) == generatedMarker;
      } finally {
        handle.closeSync();
      }
    } on FileSystemException {
      return false;
    }
  }
}
